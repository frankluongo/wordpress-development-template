<?php
/**
 * Asset loading with a dev-server switch (R6.6).
 *
 * When `npm run dev` is running it writes build/.hot containing the dev server origin,
 * and every built asset is served from there for hot reloading. Otherwise the built,
 * versioned files in build/ are used. Switching needs no code changes.
 *
 * @package StarterTheme
 */

namespace StarterTheme;

defined( 'ABSPATH' ) || exit;

/**
 * Enqueues the theme's built assets.
 */
final class Assets {

	/**
	 * Dev server origin, or null when it isn't running.
	 *
	 * @var string|null
	 */
	private ?string $hot;

	/**
	 * Constructor.
	 *
	 * @param string $dir     Absolute path to the theme.
	 * @param string $url     URL of the theme.
	 * @param string $version Theme version, used for assets without an *.asset.php file.
	 */
	public function __construct(
		private string $dir,
		private string $url,
		private string $version
	) {
		$hot_file  = $this->dir . '/build/.hot';
		$this->hot = file_exists( $hot_file ) ? untrailingslashit( trim( (string) file_get_contents( $hot_file ) ) ) : null; // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
	}

	/**
	 * Hook asset loading.
	 */
	public function register(): void {
		// Front end only.
		add_action( 'wp_enqueue_scripts', fn() => $this->enqueue_script( 'frontend' ) );
		// Front end and the editor canvas iframe.
		add_action( 'enqueue_block_assets', fn() => $this->enqueue_style( 'frontend' ) );
		// Editor UI (outside the canvas).
		add_action(
			'enqueue_block_editor_assets',
			function () {
				$this->enqueue_script( 'editor' );
				$this->enqueue_style( 'editor' );
			}
		);

		if ( $this->hot ) {
			add_filter( 'script_loader_src', array( $this, 'use_dev_server' ) );
			add_filter( 'style_loader_src', array( $this, 'use_dev_server' ) );
		}
	}

	/**
	 * Point this theme's built asset URLs at the dev server while it's running.
	 *
	 * @param string $src Asset URL.
	 */
	public function use_dev_server( $src ) {
		$build_url = trailingslashit( $this->url ) . 'build/';
		if ( $this->hot && is_string( $src ) && str_starts_with( $src, $build_url ) ) {
			$path = wp_parse_url( $build_url, PHP_URL_PATH );
			return $this->hot . $path . substr( $src, strlen( $build_url ) );
		}
		return $src;
	}

	/**
	 * Enqueue build/assets/<entry>.js if it exists.
	 *
	 * @param string $entry Entry point name.
	 */
	private function enqueue_script( string $entry ): void {
		if ( ! file_exists( $this->path( "$entry.js" ) ) ) {
			return;
		}
		$asset = $this->asset( $entry );
		wp_enqueue_script(
			"starter-theme-$entry",
			$this->asset_url( "$entry.js" ),
			$asset['dependencies'],
			$asset['version'],
			array(
				'in_footer' => true,
				'strategy'  => 'defer',
			)
		);
	}

	/**
	 * Enqueue build/assets/<entry>.css if it exists.
	 *
	 * @param string $entry Entry point name.
	 */
	private function enqueue_style( string $entry ): void {
		if ( ! file_exists( $this->path( "$entry.css" ) ) ) {
			return;
		}
		wp_enqueue_style(
			"starter-theme-$entry",
			$this->asset_url( "$entry.css" ),
			array(),
			$this->asset( $entry )['version']
		);
	}

	/**
	 * Dependencies and version generated by wp-scripts.
	 *
	 * @param string $entry Entry point name.
	 * @return array{dependencies: string[], version: string}
	 */
	private function asset( string $entry ): array {
		$file = $this->path( "$entry.asset.php" );
		$data = file_exists( $file ) ? require $file : array();
		return array(
			'dependencies' => $data['dependencies'] ?? array(),
			'version'      => $data['version'] ?? $this->version,
		);
	}

	/**
	 * Absolute path to a built asset.
	 *
	 * @param string $file File name.
	 */
	private function path( string $file ): string {
		return $this->dir . '/build/assets/' . $file;
	}

	/**
	 * URL of a built asset.
	 *
	 * @param string $file File name.
	 */
	private function asset_url( string $file ): string {
		return trailingslashit( $this->url ) . 'build/assets/' . $file;
	}
}
