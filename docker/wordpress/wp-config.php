<?php
/**
 * Local wp-config.php, driven entirely by environment variables from .env.
 * Mounted read-only into the php container; WordPress never writes to it.
 *
 * @package wp-dev-template
 */

$wp_dev_env = static function ( $key, $fallback = '' ) {
	$value = getenv( $key );
	return ( false === $value || '' === $value ) ? $fallback : $value;
};

// Database.
define( 'DB_NAME', $wp_dev_env( 'DB_NAME', 'wordpress' ) );
define( 'DB_USER', $wp_dev_env( 'DB_USER', 'wordpress' ) );
define( 'DB_PASSWORD', $wp_dev_env( 'DB_PASSWORD', 'wordpress' ) );
define( 'DB_HOST', $wp_dev_env( 'DB_HOST', 'db' ) );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );

// Updated by `npm run db:import` to match the imported dump (R5.5).
$table_prefix = $wp_dev_env( 'TABLE_PREFIX', 'wp_' ); // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited

// TLS is terminated by the shared proxy; tell WordPress the request was HTTPS (R3.5).
if ( isset( $_SERVER['HTTP_X_FORWARDED_PROTO'] ) && 'https' === $_SERVER['HTTP_X_FORWARDED_PROTO'] ) {
	$_SERVER['HTTPS'] = 'on';
}

$wp_dev_url = 'https://' . $wp_dev_env( 'SITE_DOMAIN', 'localhost' );
define( 'WP_HOME', $wp_dev_url );
define( 'WP_SITEURL', $wp_dev_url );

// Debugging (R2.9). The log is at wp-content/debug.log; tail it with `npm run logs`.
define( 'WP_ENVIRONMENT_TYPE', $wp_dev_env( 'WP_ENVIRONMENT_TYPE', 'local' ) );
define( 'WP_DEBUG', true );
define( 'WP_DEBUG_LOG', true );
define( 'WP_DEBUG_DISPLAY', false );

// `wp-scripts --hot` needs SCRIPT_DEBUG so WordPress registers the React Refresh runtime.
$wp_dev_hot_files = array_filter(
	array(
		$wp_dev_env( 'THEME_SLUG' ) ? __DIR__ . '/wp-content/themes/' . $wp_dev_env( 'THEME_SLUG' ) . '/build/.hot' : '',
		$wp_dev_env( 'PLUGIN_SLUG' ) ? __DIR__ . '/wp-content/plugins/' . $wp_dev_env( 'PLUGIN_SLUG' ) . '/build/.hot' : '',
	)
);
define( 'SCRIPT_DEBUG', (bool) array_filter( $wp_dev_hot_files, 'file_exists' ) );

// Core and plugin versions are pinned to production; never update them locally.
define( 'AUTOMATIC_UPDATER_DISABLED', true );
define( 'WP_AUTO_UPDATE_CORE', false );

// Salts, generated by `npm run setup`.
define( 'AUTH_KEY', $wp_dev_env( 'WP_AUTH_KEY', 'local-auth-key' ) );
define( 'SECURE_AUTH_KEY', $wp_dev_env( 'WP_SECURE_AUTH_KEY', 'local-secure-auth-key' ) );
define( 'LOGGED_IN_KEY', $wp_dev_env( 'WP_LOGGED_IN_KEY', 'local-logged-in-key' ) );
define( 'NONCE_KEY', $wp_dev_env( 'WP_NONCE_KEY', 'local-nonce-key' ) );
define( 'AUTH_SALT', $wp_dev_env( 'WP_AUTH_SALT', 'local-auth-salt' ) );
define( 'SECURE_AUTH_SALT', $wp_dev_env( 'WP_SECURE_AUTH_SALT', 'local-secure-auth-salt' ) );
define( 'LOGGED_IN_SALT', $wp_dev_env( 'WP_LOGGED_IN_SALT', 'local-logged-in-salt' ) );
define( 'NONCE_SALT', $wp_dev_env( 'WP_NONCE_SALT', 'local-nonce-salt' ) );

if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', __DIR__ . '/' );
}

require_once ABSPATH . 'wp-settings.php';
